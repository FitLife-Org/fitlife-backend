package com.fitlife.ai.enums;

/**
 * Kinh nghiệm tập luyện hiện tại của hội viên.
 */
public enum ExperienceLevel {

    /**
     * Người mới hoặc đã nghỉ tập trong thời gian dài.
     */
    BEGINNER,

    /**
     * Đã có nền tảng tập luyện cơ bản.
     */
    INTERMEDIATE,

    /**
     * Có kinh nghiệm tập luyện lâu dài và kỹ thuật tốt.
     */
    ADVANCED
}